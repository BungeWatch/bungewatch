import enum
import uuid
from datetime import datetime

from sqlalchemy import Text, DateTime, Enum, Integer, String, ForeignKey, func
from sqlalchemy.dialects.postgresql import UUID, JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base


class SummaryStatus(str, enum.Enum):
    draft = "draft"          # generated by AI, not yet reviewed
    reviewed = "reviewed"    # reviewer has looked at it, may still be editing
    approved = "approved"    # cleared for publishing/notification
    corrected = "corrected"  # a published version was later fixed


class Summary(Base):
    """
    A versioned, AI-generated summary of a bill. Versioned (not overwritten)
    so corrections have a history and you can tell what a user actually received.
    """
    __tablename__ = "summaries"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    bill_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("bills.id", ondelete="CASCADE"))

    version: Mapped[int] = mapped_column(Integer, default=1)

    summary_full: Mapped[str] = mapped_column(Text)

    pros: Mapped[list] = mapped_column(JSONB, default=list)
    cons: Mapped[list] = mapped_column(JSONB, default=list)
    sectors_affected: Mapped[list] = mapped_column(JSONB, default=list)

    ai_model_used: Mapped[str] = mapped_column(String(100))
    status: Mapped[SummaryStatus] = mapped_column(Enum(SummaryStatus), default=SummaryStatus.draft)

    reviewer_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), nullable=True)
    approved_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())

    bill: Mapped["Bill"] = relationship(back_populates="summaries")
